#!/usr/bin/env python3
"""Docker multi-node Nira testnet: validators (one behind a sentry), RPC node and
community nodes running the real prove loop, plus scenario tests.

  deploy/testnet/testnet.py build                      # docker image nira:local from source
  deploy/testnet/testnet.py up --validators 8 --community 6
  deploy/testnet/testnet.py status
  deploy/testnet/testnet.py test [health|sentry|community|partition|soak|all] [--soak-minutes 10]
  deploy/testnet/testnet.py down                       # stop and delete the chain data volume

Host ports (rpc0): CometBFT 36657, REST 31317, JSON-RPC 38545 / WS 38546.
"""
import argparse
import json
import subprocess
import sys
import time
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
COMPOSE = HERE / "docker-compose.yml"
PROJECT = "nira-testnet"
VOLUME = f"{PROJECT}-data"
NETWORK = f"{PROJECT}_nira"
IMAGE = "nira:local"
PORTS = {"cmt": 36657, "rest": 31317, "evm": 38545, "ws": 38546}
passed = 0


def sh(*args, check=True, capture=True, input=None):
    r = subprocess.run(args, capture_output=capture, text=True, input=input)
    if check and r.returncode:
        raise SystemExit(f"$ {' '.join(args)}\n{r.stdout}\n{r.stderr}")
    return r.stdout if capture else ""


def compose(*args, capture=True, check=True):
    return sh("docker", "compose", "-p", PROJECT, "-f", str(COMPOSE), *args, capture=capture, check=check)


def meta():
    return json.loads(sh("docker", "run", "--rm", "-v", f"{VOLUME}:/data", "--entrypoint", "cat", IMAGE, "/data/testnet.json"))


def node_json(node, path):
    """GET a CometBFT RPC path from inside a node container (works for any node)."""
    out = sh("docker", "exec", f"{PROJECT}-{node}", "curl", "-sf", "-m", "5", f"http://localhost:26657{path}", check=False)
    return json.loads(out) if out else None


def rest(path):
    with urllib.request.urlopen(f"http://127.0.0.1:{PORTS['rest']}{path}", timeout=10) as r:
        return json.load(r)


def height(node="rpc0"):
    j = node_json(node, "/status")
    return int(j["result"]["sync_info"]["latest_block_height"]) if j else -1


def ok(msg):
    global passed
    passed += 1
    print(f"ok  {msg}", flush=True)


def fail(msg):
    raise SystemExit(f"FAIL: {msg}")


def wait(cond, timeout, msg):
    end = time.time() + timeout
    while time.time() < end:
        if cond():
            return
        time.sleep(2)
    fail(msg)


# ------------------------------------------------------------------ lifecycle
def cmd_build(_):
    ver = sh("git", "-C", str(REPO), "describe", "--always").strip()
    sh("docker", "build", "-f", str(REPO / "deploy/docker/Dockerfile"), "-t", IMAGE, "--build-arg", f"VERSION={ver}",
       str(REPO), capture=False)


def write_compose(m):
    svc = []
    nodes = m["validators"] + ["sentry0", "rpc0"] + m["community"]
    for n in nodes:
        lines = [f"  {n}:", f"    image: {IMAGE}", f"    container_name: {PROJECT}-{n}", f"    hostname: {n}",
                 f"    volumes: [\"{VOLUME}:/data\"]", "    networks: [nira]", "    restart: unless-stopped",
                 "    stop_grace_period: 20s"]
        if n.startswith("cn"):
            lines += ["    entrypoint: [\"sh\", \"/opt/nira/community.sh\"]", f"    environment: {{ NODE: {n} }}"]
        else:
            lines += [f"    command: [\"start\", \"--home\", \"/data/{n}\"]"]
        if n == "rpc0":
            lines += ["    ports:", f"      - \"127.0.0.1:{PORTS['cmt']}:26657\"", f"      - \"127.0.0.1:{PORTS['rest']}:1317\"",
                      f"      - \"127.0.0.1:{PORTS['evm']}:8545\"", f"      - \"127.0.0.1:{PORTS['ws']}:8546\""]
        svc.append("\n".join(lines))
    COMPOSE.write_text("# generated by deploy/testnet/testnet.py — do not edit\nservices:\n" + "\n".join(svc) +
                       f"\nnetworks:\n  nira: {{}}\nvolumes:\n  {VOLUME}:\n    external: true\n")


def cmd_up(a):
    if COMPOSE.exists():
        compose("down", "--remove-orphans", check=False)
    sh("docker", "volume", "rm", "-f", VOLUME, check=False)
    sh("docker", "volume", "create", VOLUME)
    out = sh("docker", "run", "--rm", "-v", f"{VOLUME}:/data", "--entrypoint", "python3", IMAGE,
             "/opt/nira/gen.py", "--validators", str(a.validators), "--community", str(a.community))
    print("generated:", out.strip())
    write_compose(meta())
    compose("up", "-d", capture=False)
    wait(lambda: height() > 3, 120, "chain did not start")
    print(f"testnet up at height {height()} — REST http://127.0.0.1:{PORTS['rest']}  JSON-RPC http://127.0.0.1:{PORTS['evm']}")


def cmd_down(_):
    if COMPOSE.exists():
        compose("down", "--remove-orphans", "-t", "5", check=False)
    sh("docker", "volume", "rm", "-f", VOLUME, check=False)
    print("testnet removed")


def cmd_status(_):
    m = meta()
    for n in m["validators"] + ["sentry0", "rpc0"] + m["community"]:
        j = node_json(n, "/status")
        ni = node_json(n, "/net_info")
        h = j["result"]["sync_info"]["latest_block_height"] if j else "down"
        peers = ni["result"]["n_peers"] if ni else "-"
        print(f"{n:8} height {h:>6}  peers {peers}")


# ------------------------------------------------------------------ scenarios
def test_health(m):
    vals = rest("/cosmos/staking/v1beta1/validators?status=BOND_STATUS_BONDED&pagination.limit=100")["validators"]
    if len(vals) != len(m["validators"]):
        fail(f"{len(vals)} bonded validators, want {len(m['validators'])}")
    h = height() - 1
    commit = node_json("rpc0", f"/commit?height={h}")
    sigs = sum(1 for s in commit["result"]["signed_header"]["commit"]["signatures"] if s["block_id_flag"] == 2)
    if sigs != len(m["validators"]):
        fail(f"block {h}: {sigs}/{len(m['validators'])} signatures")
    nodes = m["validators"] + ["sentry0", "rpc0"] + m["community"]
    hashes = {n: (node_json(n, f"/block?height={h}") or {}).get("result", {}).get("block_id", {}).get("hash") for n in nodes}
    if len(set(hashes.values())) != 1:
        fail(f"nodes disagree at {h}: {hashes}")
    ok(f"{len(vals)} validators bonded, all signed block {h}; {len(nodes)} nodes agree on its hash")


def test_sentry(m):
    s, sid = m["sentried"], m["ids"][m["sentried"]]
    others = [n for n in m["validators"] + ["rpc0"] + m["community"] if n != s]
    for n in others:
        peers = {p["node_info"]["id"] for p in node_json(n, "/net_info")["result"]["peers"]}
        if sid in peers:
            fail(f"{n} is directly connected to the sentried validator {s}")
    own = [p["node_info"]["moniker"] for p in node_json(s, "/net_info")["result"]["peers"]]
    if own != ["sentry0"]:
        fail(f"{s} peers {own}, want only sentry0")
    # the sentried validator still signs (its votes travel via the sentry)
    h = height() - 1
    addr = node_json(s, "/status")["result"]["validator_info"]["address"]
    sigs = node_json("rpc0", f"/commit?height={h}")["result"]["signed_header"]["commit"]["signatures"]
    if not any(x.get("validator_address") == addr and x["block_id_flag"] == 2 for x in sigs):
        fail(f"{s} did not sign block {h}")
    ok(f"{s} is reachable only through sentry0 (no other node peers with it) and still signs block {h}")


def test_community(m):
    ep0 = int(rest("/nira/community/v1/epoch")["epoch"]["number"])
    target = max(ep0 + 2, 4)
    print(f"    waiting for community epoch {target} (now {ep0}, 20 blocks/epoch) …", flush=True)
    wait(lambda: int(rest("/nira/community/v1/epoch")["epoch"]["number"]) >= target, 600, "epochs did not advance")
    rows = []
    for c in m["community"]:
        op = sh("docker", "exec", f"{PROJECT}-{c}", "nirad", "keys", "show", "cnode", "-a",
                "--keyring-backend", "test", "--home", f"/data/{c}").strip()
        n = rest(f"/nira/community/v1/nodes/{op}")["node"]
        rows.append((c, int(n["units_total"]), int(n["rewards_total"])))
    lazy = [r[0] for r in rows if r[1] == 0 or r[2] == 0]
    if lazy:
        fail(f"community nodes without verified work or rewards: {lazy} ({rows})")
    total = sum(r[2] for r in rows) / 1e18
    ok(f"{len(rows)} community nodes proved {sum(r[1] for r in rows)} tasks and earned {total:.2f} NIRA in total "
       f"(min units {min(r[1] for r in rows)}); consensus unaffected")


def same_hash_everywhere(nodes, h):
    hs = {(node_json(n, f"/block?height={h}") or {}).get("result", {}).get("block_id", {}).get("hash") for n in nodes}
    return len(hs) == 1 and None not in hs


def test_partition(m):
    vals = m["validators"]
    nodes = vals + ["sentry0", "rpc0"] + m["community"]
    minority = vals[1:1 + (len(vals) - 1) // 3 - 0]  # < 1/3 of power
    minority = minority[: max(1, (len(vals) - 1) // 3)]
    for n in minority:
        sh("docker", "network", "disconnect", NETWORK, f"{PROJECT}-{n}")
    h0 = height()
    time.sleep(12)
    h1 = height()
    if h1 < h0 + 4:
        fail(f"majority side stalled with {len(minority)}/{len(vals)} validators cut off ({h0} → {h1})")
    stuck = {n: height(n) for n in minority}
    if any(v > h0 + 1 for v in stuck.values()):
        fail(f"isolated minority advanced: {stuck}")
    ok(f"partition {len(vals) - len(minority)}|{len(minority)}: majority kept finalising ({h0} → {h1}); isolated side stuck at ≤ {h0 + 1}")
    for n in minority:
        sh("docker", "network", "connect", NETWORK, f"{PROJECT}-{n}")
    wait(lambda: all(abs(height(n) - height()) <= 2 for n in minority), 120, "minority did not catch up")
    ok("partition healed: minority caught up by block sync")

    # ≥ 1/3 cut off → no node may finalise anything (halt, not fork)
    cut = vals[1:1 + -(-len(vals) // 3) + 0]  # ceil(N/3) validators ≥ 1/3
    for n in cut:
        sh("docker", "network", "disconnect", NETWORK, f"{PROJECT}-{n}")
    time.sleep(6)
    h2 = height()
    time.sleep(15)
    h3 = height()
    if h3 > h2 + 1:
        fail(f"chain advanced with {len(cut)}/{len(vals)} validators partitioned ({h2} → {h3})")
    ok(f"partition {len(vals) - len(cut)}|{len(cut)} (≥ 1/3 cut off): chain halted at {h3} instead of forking")
    for n in cut:
        sh("docker", "network", "connect", NETWORK, f"{PROJECT}-{n}")
    wait(lambda: height() > h3 + 3, 180, "chain did not resume after healing")
    wait(lambda: all(abs(height(n) - height()) <= 2 for n in nodes), 180, "nodes did not converge")
    check = h3 + 1
    if not same_hash_everywhere(nodes, check):
        fail(f"nodes disagree on block {check} after healing")
    ok(f"healed: chain resumed ({h3} → {height()}), all {len(nodes)} nodes agree on block {check} (no fork)")


def test_soak(m, minutes):
    loadgen = REPO / "build" / "loadgen"
    sh("go", "build", "-o", str(loadgen), "./tools/loadgen", check=True) if not loadgen.exists() else None
    key = sh("docker", "exec", f"{PROJECT}-rpc0", "sh", "-c",
             "echo y | nirad keys unsafe-export-eth-key dev1 --keyring-backend test --home /data/rpc0").strip().splitlines()[-1]
    stats0 = mem_stats()
    h0, t0, rounds, sent = height(), time.time(), 0, 0
    mon = subprocess.Popen([sys.executable, str(REPO / "scripts/monitor.py"), "--rpc", f"http://127.0.0.1:{PORTS['cmt']}",
                            "--rest", f"http://127.0.0.1:{PORTS['rest']}", "--interval", "3", "--halt-after", "30"],
                           stdout=subprocess.PIPE, text=True)
    while time.time() - t0 < minutes * 60:
        out = sh(str(loadgen), "--mode", "mixed", "--accounts", "40", "--txs", "25", "--funder-key", key,
                 "--evm-rpc", f"http://127.0.0.1:{PORTS['evm']}", "--rest", f"http://127.0.0.1:{PORTS['rest']}",
                 "--cmt", f"http://127.0.0.1:{PORTS['cmt']}", "--chain-id", m["chain_id"])
        r = json.loads(out)
        rounds, sent = rounds + 1, sent + r["included"]
    mon.terminate()
    alerts = [json.loads(l) for l in mon.stdout.read().splitlines() if l.startswith("{")]
    halts = [x for x in alerts if x["alert"] in ("halt", "comm_hook_error", "slash", "jailed")]
    h1, dur = height(), time.time() - t0
    stats1 = mem_stats()
    growth = {n: round(stats1[n] - stats0.get(n, 0), 1) for n in stats1}
    if halts:
        fail(f"alerts during soak: {halts}")
    ok(f"soak {dur / 60:.1f} min: {rounds} load rounds, {sent} txs included, {h1 - h0} blocks "
       f"({(h1 - h0) / dur:.2f} blocks/s), no halt/slash/jail/hook alerts")
    worst = max(growth.items(), key=lambda kv: kv[1])
    print(f"    memory (MiB) start→end per container: " +
          ", ".join(f"{n} {stats0.get(n, 0):.0f}→{stats1[n]:.0f}" for n in sorted(stats1)), flush=True)
    ok(f"largest container memory growth over the soak: {worst[0]} +{worst[1]} MiB")


def mem_stats():
    out = sh("docker", "stats", "--no-stream", "--format", "{{.Name}} {{.MemUsage}}")
    res = {}
    for line in out.splitlines():
        name, usage = line.split(" ", 1)
        if not name.startswith(PROJECT):
            continue
        v = usage.split("/")[0].strip()
        num = float(v[:-3]) * (1024 if v.endswith("GiB") else 1 if v.endswith("MiB") else 1 / 1024)
        res[name.replace(f"{PROJECT}-", "")] = num
    return res


def cmd_test(a):
    m = meta()
    names = ["health", "sentry", "community", "partition", "soak"] if a.scenario == "all" else [a.scenario]
    for s in names:
        print(f"== {s}", flush=True)
        if s == "soak":
            test_soak(m, a.soak_minutes)
        else:
            globals()[f"test_{s}"](m)
    print(f"\n{passed} checks passed")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build")
    up = sub.add_parser("up")
    up.add_argument("--validators", type=int, default=8)
    up.add_argument("--community", type=int, default=6)
    sub.add_parser("down")
    sub.add_parser("status")
    t = sub.add_parser("test")
    t.add_argument("scenario", nargs="?", default="all", choices=["health", "sentry", "community", "partition", "soak", "all"])
    t.add_argument("--soak-minutes", type=float, default=10)
    a = ap.parse_args()
    {"build": cmd_build, "up": cmd_up, "down": cmd_down, "status": cmd_status, "test": cmd_test}[a.cmd](a)


if __name__ == "__main__":
    main()
